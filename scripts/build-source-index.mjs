/**
 * Generates src/lib/generated/source-index.ts from the READ-WHOLE records in
 * docs/research/PAGE-SOURCES.md.
 *
 * WHY THIS EXISTS. `STATUTES` holds offence-grading tables, and it is the only
 * thing the citation schema could resolve against. Guides quote court rules and
 * procedural statutes, which carry no degrees and therefore no table, so 21 of
 * the 22 statutory spans on the two guides resolved to nothing and their pages
 * cited no sources at all. Those sources are all recorded, just in a different
 * place: PAGE-SOURCES.md, under a READ-WHOLE marker with the fetch URL on the
 * following line.
 *
 * GENERATED RATHER THAN READ AT RUNTIME so nothing in src/ reaches into docs/,
 * and so the index is a reviewable artifact in the diff. Same pattern as
 * scripts/build-maps.mjs.
 *
 * A RECORD WITHOUT A URL IS SKIPPED, not guessed at. Three markers currently
 * have no URL line (the Fla. R. Crim. P. records), and they contribute nothing
 * rather than a constructed link.
 *
 * Run: node scripts/build-source-index.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const SRC = "docs/research/PAGE-SOURCES.md";
const OUT = "src/lib/generated/source-index.ts";

const text = readFileSync(SRC, "utf8");

const records = [];
const seen = new Set();
// READ-WHOLE and PARTIAL both. The index maps a citation to the URL it was
// fetched from and asserts nothing about completeness; D26 governs what a
// partial record may support, and that is a property of the record, not of
// this lookup. A partial record still has one true source URL.
for (const m of text.matchAll(/^(?:READ-WHOLE|PARTIAL):[ \t]*(.+)\n(https?:\/\/\S+)/gm)) {
  const cite = m[1].trim();
  const url = m[2].trim().replace(/[.,]$/, "");
  if (seen.has(cite)) continue;
  seen.add(cite);
  records.push({ cite, url });
}

const markers = [...text.matchAll(/^(?:READ-WHOLE|PARTIAL):[ \t]*(.+)$/gm)].map((m) => m[1].trim());

/**
 * Hashes of every recorded line, so a renderer can ask "is this text verbatim
 * from a source?" without shipping 600KB of statute into the bundle.
 *
 * WHY THE QUESTION NEEDS ANSWERING AT ALL. `statute.body` was rendered as a
 * <blockquote cite=...> on every page, which asserts that the text came from
 * that URL. On the charge pages it does not: those bodies are authored prose
 * that quotes fragments, e.g. "The section is short enough to read whole.
 * (1)(a) The offense of battery occurs when...". 35 of 56 spans were making a
 * claim about their own provenance that was not true.
 *
 * FNV-1a rather than a crypto hash: deterministic, dependency-free, and it runs
 * in any rendering context. Collisions across ~1,500 short lines are not a
 * practical concern, and a collision would make a prose span render as a
 * quotation rather than the reverse, which the gate then catches.
 */
function fnv1a(str) {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, "0");
}

const recordedLines = [
  ...new Set(
    text
      .split("\n")
      .filter((l) => l.startsWith("> "))
      .map((l) => l.slice(2).trim().replace(/\s+/g, " "))
      .filter((l) => l.length > 0),
  ),
];
const lineHashes = [...new Set(recordedLines.map(fnv1a))].sort();
const skipped = markers.filter((c) => !seen.has(c));

mkdirSync("src/lib/generated", { recursive: true });
writeFileSync(
  OUT,
  `// GENERATED by scripts/build-source-index.mjs. Do not hand-edit.
//
// Every READ-WHOLE or PARTIAL record in docs/research/PAGE-SOURCES.md that states the URL
// it was fetched from. This is what lets a quoted court rule or procedural
// statute cite its own source: those carry no offence grading, so they have no
// table in STATUTES and nothing else could resolve them.
//
// ${records.length} records with a URL.${
    skipped.length
      ? `\n// ${skipped.length} READ-WHOLE marker(s) state no URL and are deliberately absent\n// rather than linked to a constructed address:\n${skipped.map((c) => `//   - ${c}`).join("\n")}`
      : ""
  }

export type RecordedSource = { cite: string; url: string };

export const RECORDED_SOURCES: RecordedSource[] = ${JSON.stringify(records, null, 2)};

// FNV-1a hashes of ${recordedLines.length} recorded lines, for asking whether a
// rendered span is verbatim from a source. See isRecordedVerbatim in
// src/lib/statute-links.ts.
export const RECORDED_LINE_HASHES: ReadonlySet<string> = new Set(${JSON.stringify(lineHashes)});
`,
  "utf8",
);

console.log(`wrote ${OUT}: ${records.length} sources, ${skipped.length} skipped for having no URL`);
for (const c of skipped) console.log(`  skipped: ${c}`);
